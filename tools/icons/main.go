// Command icons downloads NetrunnerDB's icon font (a symbol per cycle, plus faction and game glyphs) and writes
// static/icons/: the font and icons.css, with an .ic-<cycle code> class per symbol in the 'nrdb-icons' font family.
// The files are committed, so the app needs no server for them. Re-run it when a new cycle comes out:
//
//	go run ./tools/icons
//
// The font is from NetrunnerDB (MIT licence, © Cédric Bertolini); the symbols are the game publishers' marks.
package main

import (
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

var iconRe = regexp.MustCompile(`\.icon-([a-z0-9-]+):before\s*\{\s*content:\s*"(\\[0-9a-fA-F]+)"`)

func main() {
	out := flag.String("out", filepath.Join("static", "icons"), "directory to write netrunner.woff and icons.css to")
	flag.Parse()

	src, err := fetch("https://netrunnerdb.com/netrunnerfont.css")
	if err != nil {
		log.Fatal(err)
	}
	font, err := fetch("https://netrunnerdb.com/fonts/netrunner.woff")
	if err != nil {
		log.Fatal(err)
	}
	icons := iconRe.FindAllStringSubmatch(string(src), -1)
	if len(icons) == 0 {
		log.Fatal("no icons found in netrunnerfont.css: has its format changed?")
	}

	var b strings.Builder
	b.WriteString("/* Set symbols from NetrunnerDB's icon font (MIT licence, © Cédric Bertolini). Generated by tools/icons. */\n")
	// The font URL is relative to this file, so the app works under any sub-path.
	b.WriteString("@font-face { font-family: 'nrdb-icons'; src: url('netrunner.woff') format('woff'); font-display: block; }\n")
	for _, m := range icons {
		fmt.Fprintf(&b, ".ic-%s::before { content: \"%s\"; }\n", m[1], m[2])
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "netrunner.woff"), font, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "icons.css"), []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d icons and the font (%d bytes) to %s\n", len(icons), len(font), *out)
}

func fetch(url string) ([]byte, error) {
	client := &http.Client{Timeout: 60 * time.Second}
	req, _ := http.NewRequest("GET", url, nil)
	req.Header.Set("User-Agent", "netrunner-collection/1.0")
	resp, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("%s: HTTP %d", url, resp.StatusCode)
	}
	return io.ReadAll(resp.Body)
}
